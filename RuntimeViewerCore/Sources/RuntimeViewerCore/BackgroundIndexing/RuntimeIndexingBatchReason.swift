public enum RuntimeIndexingBatchReason: Sendable, Hashable {
    case appLaunch
    case settingsEnabled
    case manual
    /// Triggered by an entry in `Settings.Indexing.custom.entries`.
    /// `identifier` is the raw user-supplied string (full imagePath or just
    /// the image's last path component); displayed verbatim in the popover.
    case alwaysIndex(identifier: String)
    /// Shared cache images an engine that borrows them handed to the engine
    /// that owns them, which runs the batch: `borrowerName` names the
    /// borrowing engine, `reason` is why the borrower indexed them — the
    /// batch it walked them in, or the Always Index row it resolved.
    indirect case borrowed(borrowerName: String, reason: RuntimeIndexingBatchReason)
    /// Shared cache images an engine that borrows them indexes in its own
    /// serving process all the same, before it specializes a type of its
    /// own: the candidates for the type's generic arguments are the types
    /// that process has indexed.
    case specializationCandidates

    /// Batches generated by the Heuristic sub-mode (main-executable BFS).
    /// Used by `cancelBatches(matching:)` to scope cancellation when the
    /// user flips the heuristic toggle off while batches are running.
    public var isHeuristic: Bool {
        switch self {
        case .appLaunch, .settingsEnabled: return true
        case .alwaysIndex, .manual, .specializationCandidates: return false
        case .borrowed(_, let reason): return reason.isHeuristic
        }
    }

    /// Batches generated by the Custom sub-mode (always-index list).
    public var isCustom: Bool {
        switch self {
        case .alwaysIndex: return true
        case .appLaunch, .settingsEnabled, .manual, .specializationCandidates: return false
        case .borrowed(_, let reason): return reason.isCustom
        }
    }

    /// Coarse-grained grouping used by the Background Indexing popover.
    /// Batches sharing a category are displayed under a single collapsible
    /// header (e.g. several `.alwaysIndex(identifier:)` rows collapse into
    /// one "Always Index" group).
    public enum Category: Sendable, Hashable {
        case heuristic
        case alwaysIndex
        case manual
    }

    public var category: Category {
        switch self {
        case .appLaunch, .settingsEnabled: return .heuristic
        case .alwaysIndex: return .alwaysIndex
        case .manual, .specializationCandidates: return .manual
        case .borrowed(_, let reason): return reason.category
        }
    }
}
